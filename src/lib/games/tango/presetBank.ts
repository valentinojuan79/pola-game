function hashSeed(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function transformCoord(r: number, c: number, sym: number): [number, number] {
  const n = 6;
  switch (sym % 8) {
    case 0:
      return [r, c];
    case 1:
      return [c, n - 1 - r];
    case 2:
      return [n - 1 - r, n - 1 - c];
    case 3:
      return [n - 1 - c, r];
    case 4:
      return [r, n - 1 - c];
    case 5:
      return [n - 1 - r, c];
    case 6:
      return [c, r];
    case 7:
    default:
      return [n - 1 - c, n - 1 - r];
  }
}

function decodeGrid(str: string): TangoCellValue[][] {
  const grid: TangoCellValue[][] = [];
  for (let r = 0; r < 6; r++) {
    const row: TangoCellValue[] = [];
    for (let c = 0; c < 6; c++) {
      row.push(Number(str[r * 6 + c]) as TangoCellValue);
    }
    grid.push(row);
  }
  return grid;
}

/**
 * Deterministically picks a verified 6x6 Tango preset and applies
 * dihedral symmetry (8) + optional Sun/Moon swap (2) = 16x variations in 0ms.
 */
export function buildTransformedTangoPreset(
  difficulty: TangoDifficulty,
  seed: string
): TangoPuzzle {
  const list = PRESET_BANK[difficulty];
  const h = hashSeed(`${difficulty}-${seed}`);
  const base = list[h % list.length];
  const sym = (h >>> 4) % 8;
  const swapSymbols = ((h >>> 8) & 1) === 1;

  const mapVal = (v: TangoCellValue): TangoCellValue => {
    if (v === 0) return 0;
    return swapSymbols ? (v === 1 ? 2 : 1) : v;
  };

  const baseInit = decodeGrid(base.i);
  const baseSol = decodeGrid(base.s);

  const initial: TangoCellValue[][] = Array.from({ length: 6 }, () =>
    Array<TangoCellValue>(6).fill(0)
  );
  const solution: TangoCellValue[][] = Array.from({ length: 6 }, () =>
    Array<TangoCellValue>(6).fill(0)
  );

  for (let r = 0; r < 6; r++) {
    for (let c = 0; c < 6; c++) {
      const [nr, nc] = transformCoord(r, c, sym);
      initial[nr][nc] = mapVal(baseInit[r][c]);
      solution[nr][nc] = mapVal(baseSol[r][c]);
    }
  }

  const constraints: TangoConstraint[] = base.c.map(
    ([r1, c1, r2, c2, symChar]) => {
      const [nr1, nc1] = transformCoord(r1, c1, sym);
      const [nr2, nc2] = transformCoord(r2, c2, sym);
      const ordered =
        nr1 < nr2 || (nr1 === nr2 && nc1 < nc2)
          ? { r1: nr1, c1: nc1, r2: nr2, c2: nc2 }
          : { r1: nr2, c1: nc2, r2: nr1, c2: nc1 };
      return {
        ...ordered,
        type: symChar === "=" ? "same" : "diff",
      };
    }
  );

  return {
    id: `tango-${difficulty}-${seed}`,
    size: 6,
    difficulty,
    initial,
    solution,
    constraints,
  };
}

function hashSeed(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function transformCoord(
  r: number,
  c: number,
  n: number,
  rot: number,
  flipX: boolean
): ZipCoord {
  let nr = r;
  let nc = c;
  if (flipX) {
    nc = n - 1 - nc;
  }
  for (let i = 0; i < rot; i++) {
    const tmp = nr;
    nr = nc;
    nc = n - 1 - tmp;
  }
  return [nr, nc];
}

function normalizeWall(r1: number, c1: number, r2: number, c2: number): ZipWall {
  if (r1 < r2 || (r1 === r2 && c1 < c2)) return [r1, c1, r2, c2];
  return [r2, c2, r1, c1];
}

export function buildTransformedZipPreset(
  difficulty: ZipDifficulty,
  seed: string
): ZipPuzzle {
  const bank = RAW_PRESETS[difficulty];
  const h = hashSeed(seed);
  const baseIdx = h % bank.length;
  const symIdx = Math.floor(h / bank.length) % 8;
  const rot = symIdx % 4;
  const flipX = symIdx >= 4;

  const base = bank[baseIdx];
  const n = base.size;

  const solutionPath: ZipCoord[] = base.solutionPath.map(([r, c]) =>
    transformCoord(r, c, n, rot, flipX)
  );

  const waypoints: ZipWaypoint[] = base.waypoints.map(([r, c, num]) => {
    const [nr, nc] = transformCoord(r, c, n, rot, flipX);
    return { row: nr, col: nc, num };
  });

  const walls: ZipWall[] = base.walls.map(([r1, c1, r2, c2]) => {
    const [nr1, nc1] = transformCoord(r1, c1, n, rot, flipX);
    const [nr2, nc2] = transformCoord(r2, c2, n, rot, flipX);
    return normalizeWall(nr1, nc1, nr2, nc2);
  });

  return {
    id: `zip-${difficulty}-${seed}`,
    difficulty,
    size: n,
    waypoints,
    walls,
    solutionPath,
  };
}
